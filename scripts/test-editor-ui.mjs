import assert from 'node:assert/strict';
import fs from 'node:fs';
import { editorUiPlugin } from './cloud-editor.mjs';
import { articleSlug, articleRoute, isValidPin } from '../src/editor/editor-utils.ts';
assert.equal(isValidPin('4444'), true);
for (const value of ['', '1234', '444', '44444', ' 4444']) assert.equal(isValidPin(value), false);
assert.equal(articleSlug('Jyväskylän uutiset: työ & perhe'), 'jyvaskylan-uutiset-tyo-perhe');
assert.equal(articleRoute(articleSlug('Uusi toimisto avattu!')), '/uutiset/uusi-toimisto-avattu');
const folder = 'node_modules/@keystatic/core/dist';
const plugin = editorUiPlugin();
const transformed = fs.readdirSync(folder).filter(f=>f.endsWith('.js')).map(f=>plugin.transform(fs.readFileSync(`${folder}/${f}`,'utf8'), `/project/${folder}/${f}`)?.code || '').join('\n');
assert.ok(transformed.includes('"save": `Tallenna`'));
assert.ok(transformed.includes('colorScheme: "light"'));
assert.ok(transformed.includes('kontturi:editor-route'));
assert.ok(!transformed.includes('https://fonts.googleapis.com/css2?family=Inter'));
assert.ok(transformed.includes('Kirjaudu muokkaamaan'));
assert.ok(!transformed.includes("name: 'Slug',\n        key: SLUG"));
assert.ok(!transformed.includes('nameCell, ...collection.columns.map'));
assert.ok(transformed.includes("item.data?.title || ''"));
assert.ok(transformed.includes("props.collection === 'news' ? 'descending'"));
console.log('Editor PIN, Finnish slug generation, branding and route integration checks passed.');
